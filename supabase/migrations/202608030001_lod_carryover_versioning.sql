create or replace function public.get_lod_effective_level(p_assessment public.lod_assessments)
returns integer
language sql
immutable
as $$
  select case
    when coalesce(p_assessment.is_dropped, false) then null
    when p_assessment.manual_level between 1 and 5 then p_assessment.manual_level
    when coalesce(p_assessment.is_complete, false) and p_assessment.computed_level between 1 and 5 then p_assessment.computed_level
    when coalesce(p_assessment.is_carried_over, false) and p_assessment.carried_over_level between 1 and 5 then p_assessment.carried_over_level
    else null
  end;
$$;

-- Backfill only deterministic legacy carry-over rows that have one latest valid earlier source.
with carry_sources as (
  select target.id as target_id, source.id as source_id, source.year as source_year,
         public.get_lod_effective_level(source) as source_level, source.total_score as source_score
  from public.lod_assessments target
  cross join lateral (
    select candidate.*
    from public.lod_assessments candidate
    where candidate.ipo_id = target.ipo_id
      and candidate.year < target.year
      and public.get_lod_effective_level(candidate) is not null
    order by candidate.year desc, candidate.id desc
    limit 1
  ) source
  where target.is_carried_over
    and target.carried_over_from_assessment_id is null
)
update public.lod_assessments target
set carried_over_from_assessment_id = source.source_id,
    carried_over_from_year = source.source_year,
    carried_over_level = source.source_level,
    carried_over_total_score = source.source_score
from carry_sources source
where target.id = source.target_id;

