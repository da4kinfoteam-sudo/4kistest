create or replace function public.build_lod_questionnaire_config()
returns jsonb
language sql
stable
as $$
  select jsonb_build_object(
    'sections', coalesce((
      select jsonb_agg(jsonb_build_object(
        'id', section.id,
        'title', section.title,
        'code', section.code,
        'order', section."order",
        'weight', section.weight
      ) order by section."order", section.id)
      from public.lod_sections section
      where section.is_active
    ), '[]'::jsonb),
    'questions', coalesce((
      select jsonb_agg(jsonb_build_object(
        'id', question.id,
        'section_id', question.section_id,
        'text', question.text,
        'code', question.code,
        'description', question.description,
        'weight', question.weight,
        'order', question."order",
        'is_calculation_mode', coalesce(question.is_calculation_mode, false),
        'actual_label', question.actual_label,
        'total_label', question.total_label,
        'is_specific_answer_mode', coalesce(question.is_specific_answer_mode, false),
        'specific_answer_label', question.specific_answer_label
      ) order by question.section_id, question."order", question.id)
      from public.lod_questions question
      join public.lod_sections section on section.id = question.section_id and section.is_active
      where question.is_active
    ), '[]'::jsonb),
    'choices', coalesce((
      select jsonb_agg(jsonb_build_object(
        'id', choice.id,
        'question_id', choice.question_id,
        'text', choice.text,
        'points', choice.points,
        'order', choice."order"
      ) order by choice.question_id, choice."order", choice.id)
      from public.lod_choices choice
      join public.lod_questions question on question.id = choice.question_id and question.is_active
      join public.lod_sections section on section.id = question.section_id and section.is_active
      where choice.is_active
    ), '[]'::jsonb),
    'levels', coalesce((
      select jsonb_agg(jsonb_build_object(
        'id', config.id,
        'level', config.level,
        'min_score', config.min_score,
        'max_score', config.max_score
      ) order by config.level)
      from public.lod_level_configs config
    ), '[]'::jsonb)
  );
$$;

insert into public.lod_questionnaire_versions (version_number, effective_year, label, config)
